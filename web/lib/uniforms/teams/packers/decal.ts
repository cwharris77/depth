const SCALE = 0.12;
const OFFSET_X = 296;
const OFFSET_Y = 150;
const TOKEN = /[a-z]|[-+]?(?:\d*\.\d+|\d+\.?)(?:e[-+]?\d+)?/g;

function scaled(value: string): string {
  return (Number(value) * SCALE).toFixed(3);
}

// Every path command in the supplied mark is relative (m/h/v/l/z). Translating the first move
// and scaling each remaining delta preserves every foreground contour and its source paint order.
function bakePath(tx: number, ty: number, d: string): string {
  const tokens = d.match(TOKEN) ?? [];
  const out: string[] = [];
  let index = 0;
  let command = '';
  let firstMove = true;

  while (index < tokens.length) {
    if (/^[a-z]$/.test(tokens[index])) command = tokens[index++];
    if (command === 'z') {
      out.push('Z');
      command = '';
    } else if (command === 'm') {
      const x = tokens[index++];
      const y = tokens[index++];
      if (firstMove) {
        out.push(
          `M${((tx + Number(x)) * SCALE + OFFSET_X).toFixed(3)},${((ty + Number(y)) * SCALE + OFFSET_Y).toFixed(3)}`
        );
        firstMove = false;
      } else {
        out.push(`m${scaled(x)},${scaled(y)}`);
      }
      command = 'l';
    } else if (command === 'l') {
      out.push(`l${scaled(tokens[index++])},${scaled(tokens[index++])}`);
    } else if (command === 'h' || command === 'v') {
      out.push(`${command}${scaled(tokens[index++])}`);
    } else {
      throw new Error(`Unsupported Packers G path command: ${command}`);
    }
  }
  return out.join(' ');
}

