#!/usr/bin/env bash
# scripts/test-domain.sh
#
# Runs the Foundation-only DepthTests suites -- the TS/Swift fixture parity tests and the
# pure Domain logic -- through SwiftPM instead of xcodebuild, so they run anywhere a Swift
# 6 toolchain does (Linux included) in seconds, with no simulator.
#
# It writes a throwaway package under .build/domain-tests whose `Depth` module is
# Depth/Domain and whose test target symlinks the suites below. `web` is symlinked beside
# DepthTests so FixtureLoading's #filePath-relative lookup still reaches
# web/fixtures/domain. This is a fast subset, not a replacement for the targeted
# xcodebuild runs: anything touching SwiftUI, SwiftData, Supabase or the app's other
# layers still needs Xcode.
#
# Usage:
#   scripts/test-domain.sh                    # build and run every suite below
#   scripts/test-domain.sh --filter Formations # extra args go to `swift test`

set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
root=$(pwd)

# Suites that compile against Depth/Domain alone. A suite that starts depending on Data/,
# Support/ or Features/ fails to build here; drop it from this list rather than pulling
# more of the app into the package.
suites=(
    FixtureLoading.swift
    FormationsParityTests.swift
    NameFormatTests.swift
    PlayerKnownForTests.swift
    PlayerStatCategoryTests.swift
    RosterLeadersTests.swift
    StartupTeamTests.swift
    TeamEventCaptionTests.swift
    TeamEventDestinationTests.swift
    TeamSeasonStoryTests.swift
    TeamStatsMetricCatalogTests.swift
    TeamSurfacesTests.swift
)

if ! command -v swift >/dev/null 2>&1; then
    echo "test-domain: no swift toolchain on PATH (install one from swift.org or with swiftly)" >&2
    exit 1
fi

pkg="$root/.build/domain-tests"
mkdir -p "$pkg/Depth"
rm -rf "$pkg/DepthTests"
mkdir "$pkg/DepthTests"

ln -sfn "$root/Depth/Domain" "$pkg/Depth/Domain"
ln -sfn "$root/web" "$pkg/web"
for suite in "${suites[@]}"; do
    if [ ! -f "$root/DepthTests/$suite" ]; then
        echo "test-domain: DepthTests/$suite is listed but missing" >&2
        exit 1
    fi
    ln -s "$root/DepthTests/$suite" "$pkg/DepthTests/$suite"
done

cat >"$pkg/Package.swift" <<'EOF'
// swift-tools-version: 6.0
// Generated by scripts/test-domain.sh -- edit the script, not this file.
import PackageDescription

let package = Package(
    name: "DepthDomainTests",
    targets: [
        .target(name: "Depth", path: "Depth/Domain"),
        .testTarget(name: "DepthTests", dependencies: ["Depth"], path: "DepthTests"),
    ]
)
EOF

cd "$pkg"
swift test "$@"
